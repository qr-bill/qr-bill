"""Generates packages/core/src/layout/font-metrics.ts from Liberation Sans Regular and Bold.

Liberation Sans is one of the four fonts the QR-bill allows (SIX IG QR-bill v2.4, chapter 3.4), has the metrics of
Arial, and covers every character of the Swiss QR Code. The layout measures text with the advance widths written by
this script; a renderer that uses the same font gets exactly the same widths.

Usage, with fonttools installed (pip install fonttools), from the root of the repository:

    python3 scripts/generate-font-metrics.py LiberationSans-Regular.ttf LiberationSans-Bold.ttf \
        > packages/core/src/layout/font-metrics.ts

The fonts come from https://github.com/liberationfonts/liberation-fonts/releases (liberation-fonts-ttf-*.tar.gz).
"""

import hashlib
import sys

from fontTools.ttLib import TTFont

# Characters of the Swiss QR Code (chapter 4.1.1), plus the ellipsis that marks shortened text (3.5.4, 3.5.5).
RANGES = [(0x20, 0x7E), (0xA0, 0x17F), (0x218, 0x21B), (0x2026, 0x2026), (0x20AC, 0x20AC)]


def read(path):
    font = TTFont(path)
    units = font['head'].unitsPerEm
    cmap = font.getBestCmap()
    advance = font['hmtx']
    scale = lambda value: round(value * 1000 / units)
    widths = [(start, [scale(advance[cmap[cp]][0]) for cp in range(start, end + 1)]) for start, end in RANGES]
    version = font['name'].getDebugName(5)
    digest = hashlib.sha256(open(path, 'rb').read()).hexdigest()
    return font, scale, widths, version, digest


def table(name, description, widths):
    rows = ',\n'.join(f'  [0x{start:x}, [{", ".join(map(str, values))}]]' for start, values in widths)
    return (
        f'/** {description} */\n'
        f'export const {name}: readonly (readonly [number, readonly number[]])[] = [\n{rows},\n];\n'
    )


REGULAR_DESCRIPTION = (
    'Advance widths of Liberation Sans Regular, by runs of consecutive code points: [first code point, widths].'
)
BOLD_DESCRIPTION = 'Advance widths of Liberation Sans Bold, same layout as {@link REGULAR_WIDTHS}.'

regular_font, scale, regular, version, regular_digest = read(sys.argv[1])
_, _, bold, _, bold_digest = read(sys.argv[2])
ascent = scale(regular_font['hhea'].ascent)
descent = scale(-regular_font['hhea'].descent)

print(f'''// Generated by scripts/generate-font-metrics.py from Liberation Sans ({version}), SIL Open Font License 1.1.
// Do not edit by hand. Regular: sha256 {regular_digest}
// Bold: sha256 {bold_digest}

/**
 * Metrics of Liberation Sans, the reference font of the layout (SIX IG QR-bill v2.4, chapter 3.4): its advance widths
 * for the characters of the Swiss QR Code, in thousandths of the font size.
 *
 * @module
 */

/** Height of the font above the baseline, in thousandths of the font size. */
export const ASCENT = {ascent};

/** Depth of the font below the baseline, in thousandths of the font size. */
export const DESCENT = {descent};

{table('REGULAR_WIDTHS', REGULAR_DESCRIPTION, regular)}
{table('BOLD_WIDTHS', BOLD_DESCRIPTION, bold)}''')
